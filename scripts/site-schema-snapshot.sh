#!/usr/bin/env bash
#
# Regenerates dev/db/20-site-schema.sql from the Laravel repository: runs its
# migrations on a throwaway PostgreSQL 17 container, as `pulsars_site` with
# `search_path=site` (as in production), and keeps the structure of schema
# `site` only. The `api_read` views are not taken from there: dev-db-init.sh
# applies docs/contract/views.sql, the reference.
#
#     ./scripts/site-schema-snapshot.sh ../pulsars
#
# Needs docker, php and the Laravel checkout's `vendor/` (composer install).
# Run it whenever a Laravel migration changes a table, then run the tests.

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
laravel="$(cd "${1:?usage: $0 <path to the Laravel repository>}" && pwd)"
out="$root/dev/db/20-site-schema.sql"
container="pulsars-site-schema-$$"
port="${SNAPSHOT_PORT:-55461}"

docker run --detach --rm --name "$container" \
    --env POSTGRES_DB=pulsars --env POSTGRES_PASSWORD=postgres \
    --publish "127.0.0.1:$port:5432" postgres:17-alpine >/dev/null
trap 'docker stop "$container" >/dev/null' EXIT

until docker exec "$container" pg_isready --quiet --username postgres --dbname pulsars; do
    sleep 1
done
# The init scripts restart the server once: wait for the final one.
sleep 2
until docker exec "$container" pg_isready --quiet --username postgres --dbname pulsars; do
    sleep 1
done

docker exec -i --env PGPASSWORD=postgres "$container" \
    psql --username postgres --dbname pulsars --quiet --set ON_ERROR_STOP=1 \
    <"$root/dev/db/10-roles.sql"

(
    cd "$laravel"
    DB_CONNECTION=pgsql DB_HOST=127.0.0.1 DB_PORT="$port" DB_DATABASE=pulsars \
        DB_USERNAME=pulsars_site DB_PASSWORD=pulsars_site_dev DB_SEARCH_PATH=site \
        APP_KEY="base64:$(head -c 32 /dev/zero | base64)" \
        php artisan migrate --force --no-interaction </dev/null >/dev/null
)

commit="$(git -C "$laravel" rev-parse --short HEAD)"

{
    cat <<EOF
-- The Laravel \`site\` schema, as its migrations create it on PostgreSQL.
-- GENERATED by scripts/site-schema-snapshot.sh from 0jikuji0/pulsars at
-- $commit; do not edit by hand, regenerate.
--
-- The schema itself and the roles come from 10-roles.sql; Laravel's
-- \`migrations\` table is left out. Owner: pulsars_site, as in production.

EOF
    docker exec --env PGPASSWORD=postgres "$container" \
        pg_dump --username postgres --dbname pulsars --schema-only --schema=site \
        --no-privileges --no-comments --exclude-table=site.migrations |
        # psql 17.6 meta-commands, unknown to older clients; settings that
        # only matter to pg_restore; the schema, created by 10-roles.sql.
        # pg_dump's own comment blocks go too: the statements say it all.
        grep -vE '^\\(un)?restrict |^SET |^SELECT pg_catalog.set_config|^(CREATE|ALTER) SCHEMA site|^--( |$)' |
        cat -s
} >"$out"

echo "Wrote $out ($(grep -c '^CREATE TABLE' "$out") tables, from $commit)."
