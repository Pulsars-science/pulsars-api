CREATE TABLE contenu.esgi_cours (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matiere_slug varchar(80) NOT NULL REFERENCES contenu.esgi_matieres(slug),
    slug varchar(180) NOT NULL UNIQUE,
    titre varchar(180) NOT NULL,
    description varchar(1000),
    quiz jsonb NOT NULL DEFAULT '[]'::jsonb,
    flashcards jsonb NOT NULL DEFAULT '[]'::jsonb,
    fichier_pdf varchar(255),
    nom_fichier_original varchar(255),
    auteur_id bigint NOT NULL REFERENCES site.users(id),
    created_at timestamp(0) without time zone NOT NULL DEFAULT (date_trunc('second', now() AT TIME ZONE 'UTC')),
    updated_at timestamp(0) without time zone NOT NULL DEFAULT (date_trunc('second', now() AT TIME ZONE 'UTC')),
    CONSTRAINT esgi_cours_quiz_array CHECK (jsonb_typeof(quiz) = 'array'),
    CONSTRAINT esgi_cours_flashcards_array CHECK (jsonb_typeof(flashcards) = 'array')
);

CREATE INDEX esgi_cours_matiere_index
    ON contenu.esgi_cours (matiere_slug, created_at DESC, id DESC);

CREATE UNIQUE INDEX esgi_cours_fichier_pdf_unique
    ON contenu.esgi_cours (fichier_pdf)
    WHERE fichier_pdf IS NOT NULL;
